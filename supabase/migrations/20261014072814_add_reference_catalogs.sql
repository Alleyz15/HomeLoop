create extension if not exists pg_trgm with schema extensions;

create materialized view public.road_catalog as
with eligible as (
  select
    regexp_replace(
      regexp_replace(upper(btrim(road)), '[[:space:]]+', ' ', 'g'),
      '^(JALAN|JLN[.]?)[[:space:]]+',
      'JLN ',
      'i'
    ) as road_norm,
    btrim(road) as road_display,
    district,
    mukim,
    scheme,
    township,
    is_sdp,
    ptype,
    tenure,
    land_sqm,
    floor_sqm,
    ym
  from public.transactions
  where likely_primary = false
    and nullif(btrim(road), '') is not null
    and scheme is not null
    and ptype is not null
),
latest as (
  select max(ym) as max_ym
  from eligible
),
grouped as (
  select
    road_norm,
    mode() within group (order by road_display) as road_display,
    mode() within group (order by district) as district,
    mode() within group (order by mukim) as mukim,
    scheme,
    mode() within group (order by township) as township,
    mode() within group (order by is_sdp) as is_sdp,
    ptype,
    mode() within group (order by tenure) as tenure_mode,
    count(*)::bigint as n_total,
    count(*) filter (where ym >= latest.max_ym - 3)::bigint as n_recent_3y,
    mode() within group (order by round(land_sqm)) as typical_land_sqm,
    mode() within group (order by round(floor_sqm)) as typical_floor_sqm
  from eligible
  cross join latest
  group by road_norm, scheme, ptype, latest.max_ym
)
select
  grouped.road_norm,
  grouped.road_display,
  grouped.district,
  grouped.mukim,
  grouped.scheme,
  grouped.township,
  grouped.is_sdp,
  grouped.ptype,
  grouped.tenure_mode,
  grouped.n_total,
  grouped.n_recent_3y,
  grouped.typical_land_sqm,
  grouped.typical_floor_sqm,
  (
    count(*) filter (
      where round(eligible.land_sqm) = grouped.typical_land_sqm
    )::numeric / nullif(count(*), 0)
  ) as typical_share
from grouped
join eligible using (road_norm, scheme, ptype)
group by
  grouped.road_norm,
  grouped.road_display,
  grouped.district,
  grouped.mukim,
  grouped.scheme,
  grouped.township,
  grouped.is_sdp,
  grouped.ptype,
  grouped.tenure_mode,
  grouped.n_total,
  grouped.n_recent_3y,
  grouped.typical_land_sqm,
  grouped.typical_floor_sqm
with data;

create unique index road_catalog_road_scheme_ptype_idx
  on public.road_catalog (road_norm, scheme, ptype);

create index road_catalog_road_norm_trgm_idx
  on public.road_catalog
  using gin (road_norm extensions.gin_trgm_ops);

create or replace function private.refresh_road_catalog()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if session_user not in ('postgres', 'supabase_admin', 'service_role')
     and coalesce((select auth.jwt() ->> 'role'), '') <> 'service_role'
     and not (select private.is_admin()) then
    raise exception 'admin or service role required'
      using errcode = '42501';
  end if;

  refresh materialized view public.road_catalog;
end;
$$;

revoke execute on function private.refresh_road_catalog()
  from public, anon, authenticated, service_role;
grant execute on function private.refresh_road_catalog()
  to authenticated, service_role;

create or replace function public.refresh_road_catalog()
returns void
language sql
set search_path = ''
as $$
  select private.refresh_road_catalog();
$$;

revoke execute on function public.refresh_road_catalog()
  from public, anon, authenticated, service_role;
grant execute on function public.refresh_road_catalog()
  to authenticated, service_role;

create table public.sdp_launches (
  id bigint generated by default as identity primary key,
  tier text not null check (
    tier in ('selling', 'upcoming', 'check', 'under_construction')
  ),
  project text not null unique,
  township text,
  area text,
  state text,
  category text,
  property_type text,
  sdp_site_label text,
  price_from_rm numeric,
  price_note text,
  built_up_min_sqft numeric,
  built_up_max_sqft numeric,
  land_size text,
  bedrooms text,
  tenure text,
  expected_completion text,
  units integer,
  project_url text,
  extra_source text,
  listing_source text,
  checked_on date
);

create table public.backtest_ratios (
  id bigint generated by default as identity primary key,
  township text,
  scheme text,
  ptype text,
  tenure text,
  land_sqm numeric,
  floor_sqm numeric,
  ym numeric,
  actual_price numeric,
  predicted_price numeric,
  ratio numeric
);

alter table public.sdp_launches enable row level security;
alter table public.backtest_ratios enable row level security;

