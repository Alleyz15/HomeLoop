create view public.monthly_limit_usage
with (security_invoker = true)
as
with approved as (
  select
    date_trunc('month', offer_sent_at)::date as month,
    plan,
    sum(offer_amount) as used_amount
  from public.applications
  where offer_sent_at is not null
    and offer_amount is not null
    and status in (
      'offer_sent',
      'review_requested',
      'accepted',
      'espa_signed',
      'listed',
      'buyer_found',
      'guarantee_triggered',
      'old_home_completed',
      'handover'
    )
  group by date_trunc('month', offer_sent_at)::date, plan
)
select
  monthly_limits.month,
  monthly_limits.plan_a_limit,
  monthly_limits.plan_b_limit,
  coalesce(sum(approved.used_amount) filter (where approved.plan = 'A'), 0) as plan_a_used,
  coalesce(sum(approved.used_amount) filter (where approved.plan = 'B'), 0) as plan_b_used
from public.monthly_limits
left join approved using (month)
group by
  monthly_limits.month,
  monthly_limits.plan_a_limit,
  monthly_limits.plan_b_limit;

