    and indicative_high is null
    and inspection_scheduled_at is null
    and unit_type_confirmed is null
    and condition is null
    and confirmed_value is null
    and value_adjust_reason is null
    and offer_amount is null
    and offer_sent_at is null
    and offer_expires_at is null
    and review_count = 0
    and reject_reason is null
