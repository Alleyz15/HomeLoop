create table public.applications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  valuation_id uuid not null references public.valuation_requests (id),
  launch_id bigint not null references public.sdp_launches (id),
  unit_type text not null check (btrim(unit_type) <> ''),
  plan text not null check (plan in ('A', 'B')),
  new_home_price numeric not null check (new_home_price > 0),
  new_home_price_source text not null check (
    new_home_price_source in ('price_from', 'sales_quote')
  ),
  address_line text not null check (btrim(address_line) <> ''),
  postcode text not null check (btrim(postcode) <> ''),
  title_no text,
  pdpa_consent boolean not null,
  pdpa_consent_at timestamptz not null default now(),
  status text not null default 'submitted' check (
    status in (
      'submitted',
      'under_review',
      'info_requested',
      'indicative_sent',
      'owner_proceed',
      'withdrawn',
      'inspection_scheduled',
      'inspected',
      'offer_sent',
      'review_requested',
      'accepted',
      'declined',
      'expired',
      'rejected',
      'espa_signed',
      'listed',
      'buyer_found',
      'guarantee_triggered',
      'old_home_completed',
      'handover'
    )
  ),
  indicative_low numeric,
  indicative_high numeric,
  inspection_scheduled_at timestamptz,
  unit_type_confirmed boolean,
  condition text check (condition in ('good', 'fair', 'needs_repair')),
  confirmed_value numeric,
  value_adjust_reason text,
  offer_amount numeric,
  offer_sent_at timestamptz,
  offer_expires_at timestamptz,
  review_count integer not null default 0 check (
    review_count >= 0 and review_count <= 1
  ),
  reject_reason text,
  flags text[] not null default '{}'::text[],
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index applications_user_id_idx on public.applications (user_id);
