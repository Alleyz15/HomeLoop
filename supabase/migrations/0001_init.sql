create schema if not exists private;
revoke all on schema private from public, anon, authenticated;

create table public.transactions (
  id bigint generated by default as identity primary key,
  ptype text,
  district text,
  mukim text,
  scheme text,
  road text,
  tenure text,
  land_sqm numeric,
  floor_sqm numeric,
  level text,
  price numeric,
  ym numeric,
  yr integer,
  area_sqm numeric,
  township text,
  is_sdp boolean,
  likely_primary boolean
);

create index transactions_scheme_ptype_idx
  on public.transactions (scheme, ptype);
create index transactions_township_idx
  on public.transactions (township);
create index transactions_yr_idx
  on public.transactions (yr);

create table public.sdp_schemes (
  township text,
  district text,
  scheme text,
  n integer,
  primary key (township, scheme)
);

create table public.mhpi_quarterly (
  series text,
  quarter numeric,
  index_value numeric,
  source_table text,
  primary key (series, quarter)
);

create table public.cost_assumptions (
  item text primary key,
  pct_low numeric,
  pct_high numeric,
  source text
);

create table public.fairness_curve (
  plan text,
  cost numeric,
  buffer numeric,
  sdp_loss_share numeric,
  owner_pct_market numeric,
  primary key (plan, cost, buffer)
);

create table public.backtest_results (
  variant text,
  scope text,
  n integer,
  mdape numeric,
  within10 integer,
  within20 integer,
  primary key (variant, scope)
);

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  created_at timestamptz default now()
);

create table public.valuation_requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users (id) not null,
  scheme text,
  ptype text,
  land_sqm numeric,
  floor_sqm numeric,
  tenure text,
  estimate numeric,
  low numeric,
  high numeric,
  comps jsonb,
  created_at timestamptz default now()
);

create index valuation_requests_user_id_idx
  on public.valuation_requests (user_id);

alter table public.transactions enable row level security;
alter table public.sdp_schemes enable row level security;
alter table public.mhpi_quarterly enable row level security;
alter table public.cost_assumptions enable row level security;
alter table public.fairness_curve enable row level security;
alter table public.backtest_results enable row level security;
alter table public.profiles enable row level security;
alter table public.valuation_requests enable row level security;

grant usage on schema public to anon, authenticated;

revoke all on table public.transactions from anon, authenticated;
revoke all on table public.sdp_schemes from anon, authenticated;
revoke all on table public.mhpi_quarterly from anon, authenticated;
revoke all on table public.cost_assumptions from anon, authenticated;
revoke all on table public.fairness_curve from anon, authenticated;
revoke all on table public.backtest_results from anon, authenticated;
revoke all on table public.profiles from anon, authenticated;
revoke all on table public.valuation_requests from anon, authenticated;

grant select on table
  public.transactions,
  public.sdp_schemes,
  public.mhpi_quarterly,
  public.cost_assumptions,
  public.fairness_curve,
  public.backtest_results
to anon, authenticated;

grant select, update on table public.profiles to authenticated;
grant select, insert, delete on table public.valuation_requests to authenticated;

create policy "Reference transactions are publicly readable"
  on public.transactions
  for select
  to anon, authenticated
  using (true);

create policy "SDP schemes are publicly readable"
  on public.sdp_schemes
  for select
  to anon, authenticated
  using (true);

create policy "MHPI data is publicly readable"
  on public.mhpi_quarterly
  for select
  to anon, authenticated
  using (true);

create policy "Cost assumptions are publicly readable"
  on public.cost_assumptions
  for select
  to anon, authenticated
  using (true);

create policy "Fairness curves are publicly readable"
  on public.fairness_curve
  for select
  to anon, authenticated
  using (true);

create policy "Backtest results are publicly readable"
  on public.backtest_results
  for select
  to anon, authenticated
  using (true);

create policy "Users can read their own profile"
  on public.profiles
  for select
  to authenticated
  using ((select auth.uid()) = id);

create policy "Users can update their own profile"
  on public.profiles
  for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create policy "Users can read their own valuation requests"
  on public.valuation_requests
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users can create their own valuation requests"
  on public.valuation_requests
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can delete their own valuation requests"
  on public.valuation_requests
  for delete
  to authenticated
  using ((select auth.uid()) = user_id);

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id) values (new.id);
  return new;
end;
$$;

revoke execute on function private.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure private.handle_new_user();

